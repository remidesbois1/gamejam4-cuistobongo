"""PPO on the batched torch engine (schema CuistoBongo-v1), CPU or GPU.

Simulation, observations, rollouts and updates all stay on one device. Nothing
is trained unless this module is run explicitly:

    python -m rl.train --output runs/bongo-v1 --timesteps 2000000000
    python -m rl.train --resume runs/bongo-v1/final.pt --timesteps 500000000 --output runs/bongo-v1b
"""

import argparse
from importlib.metadata import version
import json
import math
from pathlib import Path
import time


def positive_int(text):
    value = int(text)
    if value <= 0:
        raise argparse.ArgumentTypeError("must be a positive integer")
    return value


def fraction(text):
    value = float(text)
    if not 0.0 <= value <= 1.0:
        raise argparse.ArgumentTypeError("must be within [0, 1]")
    return value


def nonnegative(text):
    value = float(text)
    if value < 0:
        raise argparse.ArgumentTypeError("must be >= 0")
    return value


def build_parser():
    p = argparse.ArgumentParser(description="Train a Cuisto Bongo agent with on-device PPO")
    p.add_argument("--output", type=Path, required=True, help="new run directory")
    p.add_argument("--resume", type=Path, help="continue from a checkpoint (.pt) of this schema")
    p.add_argument("--device", default="auto", help="auto, cpu, cuda or cuda:N")
    p.add_argument("--sim-dtype", choices=("float32", "float64"), default="float32",
                   help="simulation precision (float64 = exact parity with the reference engine, slower on GPU)")
    p.add_argument("--timesteps", type=positive_int, default=1_000_000_000, help="decisions to train")
    p.add_argument("--envs", type=positive_int, help="parallel games (default 16384 on GPU, 256 on CPU)")
    p.add_argument("--n-steps", type=positive_int, default=32, help="decisions per game per rollout")
    p.add_argument("--epochs", type=positive_int, default=4)
    p.add_argument("--minibatches", type=positive_int, default=8)
    p.add_argument("--lr", type=float, default=3e-4)
    p.add_argument("--final-lr-fraction", type=nonnegative, default=0.1)
    p.add_argument("--gamma", type=float, default=0.998)
    p.add_argument("--gae-lambda", type=float, default=0.95)
    p.add_argument("--clip", type=float, default=0.2)
    p.add_argument("--ent-coef", type=nonnegative, default=0.01)
    p.add_argument("--vf-coef", type=nonnegative, default=0.5)
    p.add_argument("--max-grad-norm", type=float, default=0.5)
    p.add_argument("--hidden", type=positive_int, nargs="+", default=[512, 512, 256])
    p.add_argument("--frame-skip", type=positive_int, default=6, help="ticks per decision (6 = 10 decisions/s)")
    p.add_argument("--episode-limit", type=positive_int, default=12000, help="decisions per training game")
    p.add_argument("--random-start", type=fraction, default=0.5,
                   help="fraction of training games started at a random wave 2..--max-start-wave")
    p.add_argument("--max-start-wave", type=positive_int, default=8)
    p.add_argument("--shaping", type=nonnegative, default=1.0, help="potential-based shaping coefficient")
    p.add_argument("--layout-pool", type=positive_int, default=16384,
                   help="wave layouts generated by the headless spawn code (cached under runs/cache)")
    p.add_argument("--seed", type=int, default=0)
    p.add_argument("--eval-every", type=positive_int, default=25_000_000, help="decisions between evaluations")
    p.add_argument("--eval-envs", type=positive_int, default=256, help="games per evaluation (normal start)")
    p.add_argument("--eval-episode-limit", type=positive_int, default=6300,
                   help="decisions per evaluation game (6300 = 10.5 min = 6 waves)")
    p.add_argument("--checkpoint-every", type=positive_int, default=50_000_000)
    p.add_argument("--torch-threads", type=positive_int, help="CPU threads for torch")
    p.add_argument("--no-cuda-graph", action="store_true", help="launch simulation kernels eagerly on CUDA")
    return p


class ReturnScaler:
    """Divide rewards by the running std of the discounted return (VecNormalize-style)."""

    def __init__(self, n, gamma, device):
        import torch
        self.gamma = gamma
        self.ret = torch.zeros(n, dtype=torch.float64, device=device)
        self.mean = torch.zeros((), dtype=torch.float64, device=device)
        self.var = torch.ones((), dtype=torch.float64, device=device)
        self.count = torch.tensor(1e-4, dtype=torch.float64, device=device)

    def __call__(self, reward, done):
        self.ret = self.ret * self.gamma + reward
        batch_mean, batch_var, n = self.ret.mean(), self.ret.var(unbiased=False), self.ret.numel()
        delta = batch_mean - self.mean
        total = self.count + n
        self.mean = self.mean + delta * n / total
        self.var = (self.var * self.count + batch_var * n + delta * delta * self.count * n / total) / total
        self.count = total
        self.ret = self.ret * (~done)
        return reward / (self.var.sqrt() + 1e-8)

    def state_dict(self):
        return {"mean": self.mean, "var": self.var, "count": self.count}

    def load_state_dict(self, state):
        self.mean, self.var, self.count = (state[k].to(self.mean.device) for k in ("mean", "var", "count"))


class Evaluator:
    """Deterministic masked policy, normal starts, first episode of every evaluation game."""

    def __init__(self, args, device, dtype, seed, graph, layouts):
        import torch
        from .vector.game import GraphedStep, VectorGame

        self.limit = args.eval_episode_limit
        self.game = VectorGame(args.eval_envs, device=device, dtype=dtype, frame_skip=args.frame_skip,
                               episode_limit=self.limit, seed=seed, layouts=layouts)
        self.pending = torch.ones(args.eval_envs, dtype=torch.bool, device=device)
        self.game.count_mask = self.pending
        self.step = GraphedStep(self.game) if graph else self.game.step
        self.reset = self.step.reset if graph else self.game.reset

    def __call__(self, model):
        import torch

        self.pending.fill_(True)
        obs, mask = self.reset()
        self.game.pop_stats()
        with torch.no_grad():
            for i in range(self.limit):
                logits, _ = model(obs, mask)
                obs, mask, _, terminated, truncated, _ = self.step(logits.argmax(-1))
                self.pending &= ~(terminated | truncated)
                if i % 64 == 63 and not bool(self.pending.any()):
                    break
        return self.game.pop_stats()


def main(argv=None):
    parser = build_parser()
    args = parser.parse_args(argv)
    if args.output.exists():
        parser.error("output already exists; choose a new --output directory")
    import torch
    from torch.utils.tensorboard import SummaryWriter
    from .actions import ACTION_COUNT
    from .vector.features import FEATURE_SIZE, SCHEMA
    from .vector.game import GraphedStep, VectorGame
    from .vector.layouts import load_pool
    from .vector.policy import ActorCritic, load_checkpoint, save_checkpoint
    from .rewards import RewardWeights

    device = torch.device(("cuda" if torch.cuda.is_available() else "cpu") if args.device == "auto" else args.device)
    if args.torch_threads:
        torch.set_num_threads(args.torch_threads)
    dtype = getattr(torch, args.sim_dtype)
    envs = args.envs or (16384 if device.type == "cuda" else 256)
    batch = envs * args.n_steps
    if batch % args.minibatches:
        parser.error("envs * n-steps must be divisible by --minibatches")
    minibatch = batch // args.minibatches
    torch.manual_seed(args.seed)
    # Distribution argument checks synchronise with the GPU on every step.
    torch.distributions.Distribution.set_default_validate_args(False)
    graph = device.type == "cuda" and not args.no_cuda_graph
    # TF32 matmuls for the network only; the simulation keeps --sim-dtype.
    torch.backends.cuda.matmul.allow_tf32 = True
    print(f"Layout pool: {args.layout_pool} layouts (generated on the first run, then cached)", flush=True)
    layouts = load_pool(size=args.layout_pool)

    start_step = 0
    if args.resume:
        model, payload = load_checkpoint(args.resume, device)
        model.train()
        start_step = payload.get("timesteps", 0)
    else:
        model = ActorCritic(hidden=args.hidden).to(device)
        payload = {}
    optimizer = torch.optim.Adam(model.parameters(), lr=args.lr, eps=1e-5)
    if "optimizer" in payload:
        optimizer.load_state_dict(payload["optimizer"])
    scaler = ReturnScaler(envs, args.gamma, device)
    if "return_scaler" in payload:
        scaler.load_state_dict(payload["return_scaler"])

    weights = RewardWeights()
    game = VectorGame(envs, device=device, dtype=dtype, frame_skip=args.frame_skip,
                      episode_limit=args.episode_limit, weights=weights, shaping=args.shaping, gamma=args.gamma,
                      random_start=args.random_start, max_start_wave=args.max_start_wave, seed=args.seed,
                      layouts=layouts)
    args.output.mkdir(parents=True)
    manifest = {
        "schema": SCHEMA, "algorithm": "PPO (on-device, masked actions)", "policy": "ActorCritic",
        "env_kwargs": {"frame_skip": args.frame_skip, "episode_limit": args.episode_limit},
        "sim_dtype": args.sim_dtype, "reward_weights": weights.as_dict(),
        "training_aids": {"shaping": args.shaping, "random_start": args.random_start,
                          "max_start_wave": args.max_start_wave},
        "resumed_from": str(args.resume) if args.resume else None,
        "seed": args.seed, "device": str(device), "envs": envs, "requested_timesteps": args.timesteps,
        "observation_size": FEATURE_SIZE, "actions": ACTION_COUNT,
        "layouts": {"size": layouts.size, "max_extra": layouts.max_extra},
        "versions": {"torch": version("torch")},
        "hyperparameters": {k: getattr(args, k) for k in (
            "n_steps", "epochs", "minibatches", "lr", "final_lr_fraction", "gamma", "gae_lambda", "clip",
            "ent_coef", "vf_coef", "max_grad_norm")} | {"hidden": list(model.hidden)},
    }
    (args.output / "config.json").write_text(json.dumps(manifest, indent=2), encoding="utf-8")
    writer = SummaryWriter(str(args.output / "tensorboard"))
    metrics_file = (args.output / "metrics.jsonl").open("a", encoding="utf-8")

    T, N = args.n_steps, envs
    obs_buf = torch.zeros(T, N, FEATURE_SIZE, device=device)
    mask_buf = torch.zeros(T, N, ACTION_COUNT, dtype=torch.bool, device=device)
    act_buf = torch.zeros(T, N, dtype=torch.long, device=device)
    logp_buf = torch.zeros(T, N, device=device)
    val_buf = torch.zeros(T, N, device=device)
    rew_buf = torch.zeros(T, N, device=device)
    done_buf = torch.zeros(T, N, device=device)
    updates = math.ceil(args.timesteps / batch)
    global_step = start_step
    best = payload.get("best_score", -float("inf"))
    next_eval = global_step + args.eval_every
    next_checkpoint = global_step + args.checkpoint_every

    def extra():
        return {"timesteps": global_step, "best_score": best, "return_scaler": scaler.state_dict(),
                "config": manifest}

    def log(values, step):
        for key, value in values.items():
            if isinstance(value, (int, float)):
                writer.add_scalar(key, value, step)
        metrics_file.write(json.dumps({"timesteps": step, **values}) + "\n")
        metrics_file.flush()

    step = GraphedStep(game) if graph else game.step
    obs, mask = step.reset() if graph else game.reset()
    game.pop_stats()
    evaluator = Evaluator(args, device, dtype, args.seed + 1_000_003, graph, layouts)
    started = time.perf_counter()
    try:
        for update in range(updates):
            frac = update / max(1, updates)
            lr = args.lr * (1 - frac * (1 - args.final_lr_fraction))
            for group in optimizer.param_groups:
                group["lr"] = lr
            t0 = time.perf_counter()
            with torch.no_grad():
                for t in range(T):
                    model.norm.update(obs)
                    x = model.norm(obs)
                    logits, value = model.heads(x, mask)
                    dist = torch.distributions.Categorical(logits=logits)
                    action = dist.sample()
                    obs_buf[t], mask_buf[t], act_buf[t] = x, mask, action
                    logp_buf[t], val_buf[t] = dist.log_prob(action), value
                    obs, mask, reward, terminated, truncated, final_obs = step(action)
                    done = terminated | truncated
                    reward = scaler(reward.double(), done).float()
                    # Bootstrap games cut by the decision limit (not real terminal states).
                    reward = reward + args.gamma * model(final_obs)[1] * truncated
                    rew_buf[t], done_buf[t] = reward, done.float()
                next_value = model(obs)[1]
                adv = torch.zeros_like(rew_buf)
                last = torch.zeros(N, device=device)
                for t in reversed(range(T)):
                    nonterminal = 1.0 - done_buf[t]
                    following = next_value if t == T - 1 else val_buf[t + 1]
                    delta = rew_buf[t] + args.gamma * following * nonterminal - val_buf[t]
                    last = delta + args.gamma * args.gae_lambda * nonterminal * last
                    adv[t] = last
                returns = adv + val_buf
            rollout_time = time.perf_counter() - t0
            t1 = time.perf_counter()
            b_obs, b_mask = obs_buf.reshape(batch, -1), mask_buf.reshape(batch, -1)
            b_act, b_logp = act_buf.reshape(batch), logp_buf.reshape(batch)
            b_adv, b_ret = adv.reshape(batch), returns.reshape(batch)
            stats = torch.zeros(5, device=device)
            for _ in range(args.epochs):
                perm = torch.randperm(batch, device=device)
                for start in range(0, batch, minibatch):
                    idx = perm[start:start + minibatch]
                    logits, value = model.heads(b_obs[idx], b_mask[idx])
                    dist = torch.distributions.Categorical(logits=logits)
                    logp = dist.log_prob(b_act[idx])
                    ratio = (logp - b_logp[idx]).exp()
                    a = b_adv[idx]
                    a = (a - a.mean()) / (a.std() + 1e-8)
                    pg = torch.max(-a * ratio, -a * ratio.clamp(1 - args.clip, 1 + args.clip)).mean()
                    vf = 0.5 * (value - b_ret[idx]).square().mean()
                    entropy = dist.entropy().mean()
                    loss = pg + args.vf_coef * vf - args.ent_coef * entropy
                    optimizer.zero_grad(set_to_none=True)
                    loss.backward()
                    torch.nn.utils.clip_grad_norm_(model.parameters(), args.max_grad_norm)
                    optimizer.step()
                    with torch.no_grad():
                        log_ratio = logp - b_logp[idx]
                        stats += torch.stack((pg, vf, entropy, ((ratio - 1) - log_ratio).mean(),
                                              ((ratio - 1).abs() > args.clip).float().mean())).detach()
            stats = (stats / (args.epochs * args.minibatches)).tolist()
            update_time = time.perf_counter() - t1
            global_step += batch
            var_y = b_ret.var()
            explained = float(1 - (b_ret - val_buf.reshape(batch)).var() / var_y) if var_y > 0 else 0.0
            values = {"train/policy_loss": stats[0], "train/value_loss": stats[1], "train/entropy": stats[2],
                      "train/approx_kl": stats[3], "train/clip_fraction": stats[4],
                      "train/explained_variance": explained, "train/lr": lr,
                      "time/sps": batch / (rollout_time + update_time),
                      "time/rollout_s": rollout_time, "time/update_s": update_time}
            episode = game.pop_stats()
            if episode["episodes"]:
                values.update({f"game/{k}": v for k, v in episode.items()})
            log(values, global_step)
            print(f"[{global_step:>13,}] sps={values['time/sps']:,.0f} "
                  f"ent={stats[2]:.2f} kl={stats[3]:.4f} ev={explained:.2f} "
                  + (f"| ep={episode['episodes']} score={episode['score']:.0f} waves={episode['waves']:.2f} "
                     f"pizzas={episode['pizzas']:.1f} deaths={episode['deaths']:.2f} "
                     f"len={episode['length']:.0f}" if episode["episodes"] else ""),
                  flush=True)
            if global_step >= next_eval or update == updates - 1:
                next_eval += args.eval_every
                model.eval()
                result = evaluator(model)
                model.train()
                log({f"eval/{k}": v for k, v in result.items()}, global_step)
                print(f"  eval: {json.dumps(result)}", flush=True)
                if result.get("episodes") and result["score"] > best:
                    best = result["score"]
                    save_checkpoint(args.output / "best.pt", model, extra=extra() | {"eval": result})
            if global_step >= next_checkpoint:
                next_checkpoint += args.checkpoint_every
                save_checkpoint(args.output / "checkpoints" / f"step_{global_step}.pt", model,
                                optimizer=optimizer, extra=extra())
    except KeyboardInterrupt:
        save_checkpoint(args.output / "interrupted.pt", model, optimizer=optimizer, extra=extra())
        print(f"Interrupted model saved to {args.output / 'interrupted.pt'}")
        return
    finally:
        writer.close()
        metrics_file.close()
    save_checkpoint(args.output / "final.pt", model, optimizer=optimizer, extra=extra())
    manifest["actual_timesteps"] = global_step
    manifest["wall_seconds"] = time.perf_counter() - started
    (args.output / "config.json").write_text(json.dumps(manifest, indent=2), encoding="utf-8")


if __name__ == "__main__":
    main()
