    def _orders_update(self, go, u, ev):
        alive = go[:, None] & self.order_alive
        timer = torch.where(alive, self.order_timer - DT, self.order_timer)
        expired = alive & (timer <= 0)
        change = -(self.t_points_i[self.order_recipe] * expired.long()).sum(1)
        self.order_timer = timer
        self.order_alive = self.order_alive & ~expired
        self.score = self.score + change
        self._add(ev, "score", change)
        self._add(ev, "expired", expired.sum(1))
        empty = go & (~self.order_alive).any(1)
        self.spawn_timer = torch.where(empty, self.spawn_timer + DT, self.spawn_timer)
        new = empty & (self.spawn_timer >= R.ORDER_SPAWN_TIME)
        self.spawn_timer = torch.where(new, 0.0, self.spawn_timer)
        slot = _first(~self.order_alive) & new[:, None]
        recipe = (u * len(R.RECIPES)).long().clamp(max=len(R.RECIPES) - 1)
        max_time = (self.t_time[recipe] * self.time_mult)[:, None]
        self.order_alive = self.order_alive | slot
        self.order_recipe = torch.where(slot, recipe[:, None], self.order_recipe)
        self.order_max_time = torch.where(slot, max_time, self.order_max_time)
        self.order_timer = torch.where(slot, max_time, self.order_timer)

    def _bonus_update(self, go, ev):
        m2 = go[:, None]
        prx, pry = self.p_rx[:, None], self.p_ry[:, None]
        alive = m2 & self.bomb_alive
        if self._any(alive):
            loose = alive & ~self.bomb_attached
            attach = loose & _collide(prx, pry, PS, PS, self.bomb_rx, self.bomb_ry, R.BOMB_SIZE, R.BOMB_SIZE) & \
                (self.bomb_dim == self.dim[:, None])
            held = alive & self.bomb_attached
            self.bomb_timer = torch.where(held, self.bomb_timer + DT, self.bomb_timer)
            self.bomb_rx = torch.where(held, prx + HALF_PLAYER - R.BOMB_SIZE // 2, self.bomb_rx)
            self.bomb_ry = torch.where(held, pry - 10 - R.BOMB_SIZE, self.bomb_ry)
            boom = held & (self.bomb_timer >= R.BOMB_FUSE)
            self.bomb_attached = self.bomb_attached | attach
            self.bomb_alive = self.bomb_alive & ~boom
            exploding = boom.any(1)
            if self._any(exploding):
                first = _first(boom)
                ex = (self.bomb_rx * first).sum(1) + R.BOMB_SIZE // 2
                ey = (self.bomb_ry * first).sum(1) + R.BOMB_SIZE // 2
                self._explode(exploding, ex, ey, ev)
        self.pill_timer = torch.where(go, (self.pill_timer - DT).clamp(min=0), self.pill_timer)
        taken = m2 & self.pill_alive & _collide(prx, pry, PS, PS, self.pill_rx, self.pill_ry, R.PILL_SIZE, R.PILL_SIZE)
        self.pill_timer = torch.where(taken.any(1), float(R.PILL_DURATION_TIME), self.pill_timer)
        self.pill_alive = self.pill_alive & ~taken

    def _explode(self, mask, ex, ey, ev):
        """``_explode``: enemies of the player's dimension, then resources, within BOMB_RADIUS."""
        m2 = mask[:, None]
        ex, ey = ex[:, None], ey[:, None]
        r2 = R.BOMB_RADIUS ** 2
        dx, dy = self.en_rx + self.en_size // 2 - ex, self.en_ry + self.en_size // 2 - ey
        doomed = m2 & self.en_alive & (dx * dx + dy * dy < r2) & (self.en_dim == self.dim[:, None])
        kind = self.res_kind
        dx = self.res_rx + self.t_res_w[kind] // 2 - ex
        dy = self.res_ry + self.t_res_h[kind] // 2 - ey
        hit = m2 & self.res_alive & (dx * dx + dy * dy < r2) & (self.dim != 1)[:, None] & (self.res_hit_timer <= 0)
        self.res_hp = self.res_hp - hit.long() * 100
        self.res_hit_timer = torch.where(hit, R.HIT_COOLDOWN, self.res_hit_timer)
        broken = hit & (self.res_hp <= 0)
        tomatoes = doomed & (self.en_kind == R.TOMATO_ENEMY)
        self._append_rdrops(torch.cat((tomatoes, broken), 1),
                            torch.cat((torch.full_like(self.en_kind, R.TOMATO), self.t_res_drop[kind]), 1),
                            torch.cat((self.en_rx, self.res_rx), 1), torch.cat((self.en_ry, self.res_ry), 1))
        self.en_alive = self.en_alive & ~doomed
        self.res_alive = self.res_alive & ~broken
        self._add(ev, "kills", doomed.sum(1))
        self._add(ev, "harvested", broken.sum(1))

    def _end_wave(self, end, u, wave, ev):
        self.pill_timer = torch.where(end, 0.0, self.pill_timer)
        one = torch.ones_like(self.p_speed_mult)
        self.p_speed_mult = torch.where(end, one, self.p_speed_mult)
        self.cd_limit_mult = torch.where(end, one, self.cd_limit_mult)
        self.menu_open = self.menu_open & ~end
        won = end & (self.round_p >= self.pizza_goal)
        lost = end & ~won
        self.phase = torch.where(won, SHOP, torch.where(lost, OVER, self.phase))
        self._add(ev, "game_over", lost)
        self.wave_timer = torch.where(won, float(R.SHOP_DURATION), self.wave_timer)
        self._reset_orders(won, u[:, 0])
        self.shop_cards = torch.where(won[:, None], self._sample_cards(u[:, 1:]), self.shop_cards)
        self._add(ev, "waves", won)
        leave = won & ~self._can_buy_cards().any(1)
        if self._any(leave):
            self._leave_shop(leave, wave)

    # ------------------------------------------------------- headless bridge
    def load(self, i, engine):
        """Copy the state of a headless ``Engine`` into game ``i`` (lists become compact slots)."""
        e, p = engine, engine.player
        none = lambda v: -1 if v is None else v  # noqa: E731
        values = {
            "phase": e.phase, "wave_num": e.wave_num, "wave_timer": e.wave_timer, "score": e.score,
            "pizza_goal": e.pizza_goal, "round_p": e.round_p, "extra": e.extra, "pizzas_made": e.pizzas_made,
            "menu_open": e.menu_open, "last_weapon": e.last_weapon, "last_bonus": none(e.last_bonus),
            "malus": none(e.malus), "bonus": none(e.bonus), "pill_timer": e.pill_timer, "time_mult": e.time_mult,
            "spawn_timer": e.spawn_timer, "dim": e.dim, "in_portal": e.in_portal, "items_flee": e.items_flee,
            "oven_dim": e.oven_dim, "oven_active": e.oven_active, "cd": e.cd, "cd_limit": e.cd_limit,
            "cd_limit_mult": e.cd_limit_mult, "upgrade_costs": e.upgrade_costs, "shop_cards": e.shop_cards,
            "order_alive": [o is not None for o in e.orders],
            "order_recipe": [o.recipe if o else 0 for o in e.orders],
            "order_max_time": [o.max_time if o else 0.0 for o in e.orders],
            "order_timer": [o.timer if o else 0.0 for o in e.orders],
            "p_x": p.x, "p_y": p.y, "p_vel": p.vel, "p_hp": p.hp, "p_max_hp": p.max_hp, "p_inv_timer": p.inv_timer,
            "p_last_dx": p.last_dx, "p_last_dy": p.last_dy, "p_dash_timer": p.dash_timer, "p_dash_vx": p.dash_vx,
            "p_dash_vy": p.dash_vy, "p_speed_mult": p.speed_mult, "p_rx": p.rx, "p_ry": p.ry, "p_cap": p.cap,
            "p_weapon": p.weapon, "p_inventory": p.inventory,
            "rdrop_count": len(e.res_drops), "en_count": len(e.enemies), "edrop_count": len(e.enemy_drops),
        }
        for field in ("x", "y", "vx", "vy", "tvx", "tvy", "move_timer", "rx", "ry", "moving"):
            values["portal_" + field] = [getattr(q, field) for q in e.portals]
        groups = (
            ("note", e.notes, self.note_slots, ("x", "y", "dx", "dy", "timer")),
            ("res", e.res, self.res_slots, ("kind", "rx", "ry", "hp", "hit_timer")),
            ("rdrop", e.res_drops, self.rdrop_slots, ("kind", "rx", "ry")),
            ("en", e.enemies, self.enemy_slots, ("kind", "giant", "x", "y", "rx", "ry", "size", "hp", "max_hp",
                                                  "hit_timer", "dim", "shoot_cd", "move_timer", "wx", "wy",
                                                  "timer", "vx", "vy", "move_state", "state")),
            ("edrop", e.enemy_drops, self.edrop_slots, ("rx", "ry", "dim")),
            ("proj", e.projectiles, self.proj_slots, ("x", "y", "vx", "vy", "timer", "rx", "ry", "size", "dim")),
            ("bomb", e.bombs, self.bomb_slots, ("attached", "rx", "ry", "dim", "timer")),
            ("pill", e.pills, self.pill_slots, ("rx", "ry")),
        )
        for prefix, items, slots, fields in groups:
            if len(items) > slots:
                raise ValueError(f"{len(items)} {prefix} entries exceed {slots} slots")
            pad = slots - len(items)
            values[prefix + "_alive"] = [True] * len(items) + [False] * pad
            for field in fields:
                values[f"{prefix}_{field}"] = [getattr(x, field) for x in items] + [0] * pad
        # One host tensor per dtype, then one copy per field into the rows of game i.
        by_dtype = {}
        for name, value in values.items():
            t = getattr(self, name)
            flat = value if isinstance(value, list) else [value]
            by_dtype.setdefault(t.dtype, []).append((t[i], flat))
        for dtype, fields in by_dtype.items():
            host = torch.tensor([x for _, flat in fields for x in flat], dtype=dtype, device=self.device)
            parts = host.split([len(flat) for _, flat in fields])
            for (row, _), part in zip(fields, parts):
                row.copy_(part.view(row.shape))

    def to_engine(self, i):
        """Game ``i`` as a headless ``Engine`` (``rng=None``), for tests and debugging."""
        v = {name: getattr(self, name)[i].tolist() for name, _, _ in self.state_spec()}
        e = Engine.__new__(Engine)
        e.rng, e.events, e.ticks = None, Events(), 0
        for name in ("phase", "wave_num", "wave_timer", "score", "pizza_goal", "round_p", "extra", "pizzas_made",
                     "menu_open", "last_weapon", "pill_timer", "time_mult", "spawn_timer", "dim", "in_portal",
                     "items_flee", "oven_dim", "oven_active", "cd", "cd_limit", "cd_limit_mult", "upgrade_costs",
                     "shop_cards"):
            setattr(e, name, v[name])
        for name in ("last_bonus", "malus", "bonus"):
            setattr(e, name, None if v[name] < 0 else v[name])
        e.orders = []
        for k in range(R.ORDER_SLOTS):
            if v["order_alive"][k]:
                o = Order.__new__(Order)
                o.recipe, o.max_time, o.timer = v["order_recipe"][k], v["order_max_time"][k], v["order_timer"][k]
                e.orders.append(o)
            else:
                e.orders.append(None)
        p = e.player = Player()
        for field in ("x", "y", "vel", "hp", "max_hp", "inv_timer", "last_dx", "last_dy", "dash_timer", "dash_vx",
                      "dash_vy", "speed_mult", "rx", "ry", "cap", "weapon", "inventory"):
            setattr(p, field, v["p_" + field])
        e.portals = []
        for k in range(PORTALS):
            q = Portal(0, 0)
            for field in ("x", "y", "vx", "vy", "tvx", "tvy", "move_timer", "rx", "ry", "moving"):
                setattr(q, field, v["portal_" + field][k])
            e.portals.append(q)

        def items(prefix, make, fields, order=None):
            slots = [k for k, alive in enumerate(v[prefix + "_alive"]) if alive]
            if order is not None:
                slots.sort(key=order)
            out = []
            for k in slots:
                x = make()
                for field in fields:
                    setattr(x, field, v[f"{prefix}_{field}"][k])
                out.append(x)
            return out

        # Notes: list order is birth order, i.e. decreasing timer.
        e.notes = items("note", lambda: Note.__new__(Note), ("x", "y", "dx", "dy", "timer"),
                        order=lambda k: -v["note_timer"][k])
        specs = {spec[0]: spec for spec in R.RESOURCE_TYPES}
        e.res = []
        for k, alive in enumerate(v["res_alive"]):
            if alive:
                r = Resource(specs[v["res_kind"][k]], v["res_rx"][k], v["res_ry"][k], 0)
                r.hp, r.hit_timer = v["res_hp"][k], v["res_hit_timer"][k]
                e.res.append(r)
        e.res_drops = items("rdrop", lambda: Drop(0, 0, 0), ("kind", "rx", "ry"))
        e.enemy_drops = items("edrop", lambda: Drop(R.TOMATO, 0, 0), ("rx", "ry", "dim"))
        e.enemies = items("en", Enemy, ("kind", "giant", "x", "y", "rx", "ry", "size", "hp", "max_hp", "hit_timer",
                                        "dim", "shoot_cd", "move_timer", "wx", "wy", "timer", "vx", "vy",
                                        "move_state", "state"))
        e.projectiles = items("proj", lambda: Projectile.__new__(Projectile),
                              ("x", "y", "vx", "vy", "timer", "rx", "ry", "size", "dim"))
        e.bombs = items("bomb", lambda: Bomb(0, 0), ("attached", "rx", "ry", "dim", "timer"))
        e.pills = items("pill", lambda: Pill(0, 0, 0.0), ("rx", "ry"))
        return e


