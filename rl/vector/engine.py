def _collide(ax, ay, aw, ah, bx, by, bw, bh):
    """pygame.Rect.colliderect for non-empty integer rects (broadcasting)."""
    return (ax < bx + bw) & (ay < by + bh) & (ax + aw > bx) & (ay + ah > by)


def _uniform(u, a, b):
    """``random.uniform(a, b)`` for an injected ``u = random()``."""
    return a + (b - a) * u


def _first(mask, dim=-1):
    """One-hot of the first true entry along ``dim``."""
    return mask & (mask.long().cumsum(dim) == 1)


def _trunc(x):
    return torch.trunc(x).long()


class VectorEngine:
    """``num_envs`` independent games advanced together, one decision per ``step``.

    Games in PLAY tick, games in SHOP buy, games OVER stay frozen until
    ``reset(mask)`` (no hidden auto-reset).
    """

    def __init__(self, num_envs, *, device="cpu", dtype=torch.float64, frame_skip=6, seed=0, layouts=None,
                 max_extra=MAX_EXTRA):
        if num_envs < 1:
            raise ValueError("num_envs must be positive")
        if type(frame_skip) is not int or frame_skip < 1:
            raise ValueError("frame_skip must be a positive integer")
        self.n = num_envs
        self.device = torch.device(device)
        self.dtype = dtype
        self.frame_skip = frame_skip
        self.max_extra = max_extra
        self.squid_spots = R.BASE_SQUIDS + max_extra
        self.tomato_slots = R.BASE_TOMATOES + max_extra
        self.enemy_slots = self.squid_spots + self.tomato_slots + EXTRA_ENEMY_SLOTS
        self.res_slots = RES_SLOTS
        self.rdrop_slots = RES_SLOTS + self.tomato_slots
        self.edrop_slots = self.tomato_slots
        self.proj_slots, self.note_slots = PROJ_SLOTS, NOTE_SLOTS
        self.bomb_slots, self.pill_slots = BOMB_SLOTS, PILL_SLOTS
        self._host_branches = self.device.type == "cpu"
        self.gen = torch.Generator(device=self.device)
        self.gen.manual_seed(seed)
        if layouts is None:
            layouts = load_pool(max_extra=max_extra)
        if not isinstance(layouts, LayoutPool) or layouts.max_extra < max_extra:
            raise ValueError("layouts must be a LayoutPool with max_extra >= the engine's")
        self._build_tables(layouts)
        for name, kind, size in self.state_spec():
            shape = (self.n,) if size is None else (self.n, size)
            setattr(self, name, torch.zeros(shape, dtype=self._dtype_of(kind), device=self.device))
        self.reset(torch.ones(self.n, dtype=torch.bool, device=self.device))

    # ------------------------------------------------------------------ state
    def state_spec(self):
        """``(name, kind, size)`` of every state tensor; kind in f/i/b, size None for [N]."""
        groups = (
            (None, "i", "phase wave_num score pizza_goal round_p extra pizzas_made last_weapon last_bonus malus "
                        "bonus dim oven_dim p_rx p_ry p_cap p_weapon rdrop_count en_count edrop_count"),
            (None, "f", "wave_timer pill_timer time_mult spawn_timer cd cd_limit cd_limit_mult p_x p_y p_vel p_hp "
                        "p_max_hp p_inv_timer p_last_dx p_last_dy p_dash_timer p_dash_vx p_dash_vy p_speed_mult"),
            (None, "b", "menu_open in_portal items_flee oven_active"),
            (len(R.UPGRADES), "i", "upgrade_costs"),
            (R.SHOP_CARDS, "i", "shop_cards"),
            (3, "i", "p_inventory"),
            (R.ORDER_SLOTS, "b", "order_alive"),
            (R.ORDER_SLOTS, "i", "order_recipe"),
            (R.ORDER_SLOTS, "f", "order_max_time order_timer"),
            (PORTALS, "f", "portal_x portal_y portal_vx portal_vy portal_tvx portal_tvy portal_move_timer"),
            (PORTALS, "i", "portal_rx portal_ry"),
            (PORTALS, "b", "portal_moving"),
            (self.note_slots, "b", "note_alive"),
            (self.note_slots, "f", "note_x note_y note_dx note_dy note_timer"),
            (self.res_slots, "b", "res_alive"),
            (self.res_slots, "i", "res_kind res_rx res_ry res_hp"),
            (self.res_slots, "f", "res_hit_timer"),
            (self.rdrop_slots, "b", "rdrop_alive"),
            (self.rdrop_slots, "i", "rdrop_kind rdrop_rx rdrop_ry"),
            (self.enemy_slots, "b", "en_alive en_giant"),
            (self.enemy_slots, "i", "en_kind en_rx en_ry en_size en_dim en_move_state en_state"),
            (self.enemy_slots, "f", "en_x en_y en_hp en_max_hp en_hit_timer en_shoot_cd en_move_timer en_wx en_wy "
                                    "en_timer en_vx en_vy"),
            (self.edrop_slots, "b", "edrop_alive"),
            (self.edrop_slots, "i", "edrop_rx edrop_ry edrop_dim"),
            (self.proj_slots, "b", "proj_alive"),
            (self.proj_slots, "f", "proj_x proj_y proj_vx proj_vy proj_timer"),
            (self.proj_slots, "i", "proj_rx proj_ry proj_size proj_dim"),
            (self.bomb_slots, "b", "bomb_alive bomb_attached"),
            (self.bomb_slots, "i", "bomb_rx bomb_ry bomb_dim"),
            (self.bomb_slots, "f", "bomb_timer"),
            (self.pill_slots, "b", "pill_alive"),
            (self.pill_slots, "i", "pill_rx pill_ry"),
        )
        return [(name, kind, size) for size, kind, names in groups for name in names.split()]

    def _dtype_of(self, kind):
        return {"f": self.dtype, "i": torch.int64, "b": torch.bool}[kind]

    def _build_tables(self, pool):
        d, f, i64 = self.device, self.dtype, torch.int64
        self.t_need = torch.tensor([r[1] for r in R.RECIPES], dtype=i64, device=d)
        self.t_points = torch.tensor([r[2] for r in R.RECIPES], dtype=f, device=d)
        self.t_points_i = torch.tensor([int(r[2]) for r in R.RECIPES], dtype=i64, device=d)
        self.t_time = torch.tensor([r[3] for r in R.RECIPES], dtype=f, device=d)
        specs = {spec[0]: spec for spec in R.RESOURCE_TYPES}
        kinds = range(len(specs))
        self.t_res_w = torch.tensor([specs[k][4] for k in kinds], dtype=i64, device=d)
        self.t_res_h = torch.tensor([specs[k][5] for k in kinds], dtype=i64, device=d)
        self.t_res_hp = torch.tensor([specs[k][6] for k in kinds], dtype=i64, device=d)
        self.t_res_drop = torch.tensor([specs[k][7] for k in kinds], dtype=i64, device=d)
        self.t_move_dx = torch.tensor([m[0] for m in MOVES], dtype=i64, device=d)
        self.t_move_dy = torch.tensor([m[1] for m in MOVES], dtype=i64, device=d)
        self.t_portal_x0 = torch.tensor([p[0] for p in R.PORTAL_POSITIONS], dtype=i64, device=d)
        self.t_portal_y0 = torch.tensor([p[1] for p in R.PORTAL_POSITIONS], dtype=i64, device=d)
        # Roulette: the spin stops at the first tick whose accumulated time exceeds
        # the spin duration; the number of index increments only depends on that tick.
        totals, total = [], 0.0
        for _ in range(ROULETTE_TICKS):
            total += DT
            totals.append(total)
        huge = 1 << 40
        counts = [0] + [roulette_index(totals[k - 2] if k >= 2 else 0.0, huge) for k in range(1, ROULETTE_TICKS + 1)]
        self.t_spin_totals = torch.tensor(totals, dtype=torch.float64, device=d)
        self.t_spin_count = torch.tensor(counts, dtype=i64, device=d)
        self.t_slot_e = torch.arange(self.enemy_slots, device=d)
        self.t_slot_b = torch.arange(self.bomb_slots, device=d)
        self.t_slot_o = torch.arange(R.ORDER_SLOTS, device=d)
        self.t_slot_r = torch.arange(self.rdrop_slots, device=d)
        self.t_slot_d = torch.arange(self.edrop_slots, device=d)
        self.t_upgrades = torch.arange(len(R.UPGRADES), device=d)
        self.t_not_self = ~torch.eye(self.enemy_slots, dtype=torch.bool, device=d)
        self.t_slot_p = torch.arange(self.pill_slots, device=d)
        self.t_slot_c = torch.arange(R.SHOP_CARDS, device=d)
        spots = {"squid": self.squid_spots, "tomato": self.tomato_slots}
        layout = {}
        for name, array in pool.arrays.items():
            t = torch.as_tensor(array, device=d)
            group = name.rsplit("_", 1)[0]
            if group in spots:
                t = t[:, :spots[group]]
            layout[name] = t.to(f) if t.is_floating_point() else t
        self.layout = layout
        self.layout_count = pool.size

    def rand(self, *shape):
        """Uniform [0, 1) draws of the engine dtype (the only source of randomness)."""
        return torch.rand(*shape, generator=self.gen, device=self.device, dtype=self.dtype)

    def _any(self, mask):
        """Host branch hint: False only when ``_host_branches`` proves no game needs the work."""
        return not self._host_branches or bool(mask.any())

    def _zero_events(self):
        return {key: torch.zeros(self.n, dtype=self.dtype, device=self.device) for key in EVENT_KEYS}

    @staticmethod
    def _add(ev, key, value):
        ev[key] = ev[key] + value

    # ----------------------------------------------------------- draws per tick
    def _tick_draws(self):
        """Fixed draws of one tick: portals [N,4,4], enemies [N,E,3], new order [N], wave end [N,4]."""
        n = self.n
        return (self.rand(n, PORTALS, 4), self.rand(n, self.enemy_slots, 3), self.rand(n), self.rand(n, 4),
                self._wave_draws())

    def _wave_draws(self):
        """Fixed draws of a possible wave start: roulette [N,3], layout [N], enemies [N,E], bombs [N,9], pills [N]."""
        n = self.n
        return {"roulette": self.rand(n, 3), "layout": self.rand(n), "enemy": self.rand(n, self.enemy_slots),
                "bomb": self.rand(n, 1 + self.bomb_slots), "pill": self.rand(n)}

    # ------------------------------------------------------------------ reset
    def reset(self, mask):
        """``Game.start()`` (``Engine.reset``) in the games of ``mask``."""
        mask = mask.to(device=self.device, dtype=torch.bool)
        m2 = mask[:, None]
        u_orders, u_cards, wave = self.rand(self.n), self.rand(self.n, 3), self._wave_draws()

        def put(name, value, m=mask):
            setattr(self, name, torch.where(m, value, getattr(self, name)))

        for name, value in (("phase", PLAY), ("wave_num", 1), ("wave_timer", R.WAVE_DURATION), ("score", 0),
                            ("pizza_goal", R.INITIAL_PIZZA_GOAL), ("round_p", 0), ("extra", 0), ("pizzas_made", 0),
                            ("menu_open", False), ("last_weapon", R.DRUM), ("last_bonus", -1), ("malus", -1),
                            ("bonus", -1), ("pill_timer", 0.0), ("time_mult", 1.0), ("spawn_timer", 0.0), ("dim", 1),
                            ("in_portal", False), ("items_flee", False), ("oven_dim", 1), ("oven_active", False),
                            ("cd", 0.0), ("cd_limit", R.CD_LIMIT), ("cd_limit_mult", 1.0),
                            ("p_vel", R.PLAYER_SPEED), ("p_max_hp", R.PLAYER_HP), ("p_inv_timer", 0.0),
                            ("p_dash_vx", 0.0), ("p_dash_vy", 0.0), ("p_cap", R.INVENTORY_CAP), ("p_weapon", R.DRUM)):
            put(name, value)
        put("upgrade_costs", R.UPGRADE_COST, m2)
        self._respawn(mask)
        for name in ("portal_vx", "portal_vy", "portal_tvx", "portal_tvy", "portal_move_timer"):
            put(name, 0.0, m2)
        for name in ("note_alive", "bomb_alive", "pill_alive"):
            put(name, False, m2)
        self._reset_orders(mask, u_orders)
        put("shop_cards", self._sample_cards(u_cards), m2)
        malus = torch.full_like(self.malus, -1)
        layout = self._layout_index(wave)
        self._spawn_wave(mask, malus, layout, wave)
        self._apply_malus(mask, malus)
        self._new_round_bonus(mask, torch.full_like(self.bonus, -1), layout, wave)

    def _respawn(self, mask):
        """Player.respawn."""
        f = self.dtype
        self.p_hp = torch.where(mask, self.p_max_hp, self.p_hp)
        self.p_x = torch.where(mask, torch.full_like(self.p_x, float(R.SPAWN_X)), self.p_x)
        self.p_y = torch.where(mask, torch.full_like(self.p_y, float(R.SPAWN_Y)), self.p_y)
        self.p_rx = torch.where(mask, R.SPAWN_X, self.p_rx)
        self.p_ry = torch.where(mask, R.SPAWN_Y, self.p_ry)
        self.p_inventory = torch.where(mask[:, None], 0, self.p_inventory)
        self.p_last_dx = torch.where(mask, torch.ones((), dtype=f, device=self.device), self.p_last_dx)
        self.p_last_dy = torch.where(mask, 0.0, self.p_last_dy)
        self.p_dash_timer = torch.where(mask, 0.0, self.p_dash_timer)
        self.p_speed_mult = torch.where(mask, torch.ones((), dtype=f, device=self.device), self.p_speed_mult)

    def _reset_orders(self, mask, u):
        """``_reset_orders``: one new order in slot 0, the others empty."""
        recipe = (u * len(R.RECIPES)).long().clamp(max=len(R.RECIPES) - 1)
        first = mask[:, None] & (self.t_slot_o == 0)
        self.order_alive = torch.where(mask[:, None], self.t_slot_o == 0, self.order_alive)
        max_time = self.t_time[recipe] * self.time_mult
        self.order_recipe = torch.where(first, recipe[:, None], self.order_recipe)
        self.order_max_time = torch.where(first, max_time[:, None], self.order_max_time)
        self.order_timer = torch.where(first, max_time[:, None], self.order_timer)
        self.spawn_timer = torch.where(mask, 0.0, self.spawn_timer)

    def _sample_cards(self, u):
        """``random.sample(range(5), 3)`` (pool algorithm of ``random.Random.sample``)."""
        n_up = len(R.UPGRADES)
        pool = self.t_upgrades.expand(self.n, n_up)
        out = []
        for i in range(R.SHOP_CARDS):
            j = (u[:, i] * (n_up - i)).long().clamp(max=n_up - i - 1)[:, None]
            out.append(pool.gather(1, j))
            pool = pool.scatter(1, j, pool[:, n_up - i - 1:n_up - i])
        return torch.cat(out, 1)

    # ------------------------------------------------------------ wave start
    def _layout_index(self, wave):
        return (wave["layout"] * self.layout_count).long().clamp(max=self.layout_count - 1)

    def begin_wave(self, mask, malus, weapon, bonus, wave=None):
        """``Engine._leave_shop`` after the roulette, in the games of ``mask``.

        ``malus``/``weapon``/``bonus`` are int64 [N] (never -1). ``wave`` holds
        the draws of ``_wave_draws`` (drawn here when omitted).
        """
        mask = mask.to(device=self.device, dtype=torch.bool)
        malus = malus.to(device=self.device, dtype=torch.int64)
        weapon = weapon.to(device=self.device, dtype=torch.int64)
        bonus = bonus.to(device=self.device, dtype=torch.int64)
        if wave is None:
            wave = self._wave_draws()
        self.phase = torch.where(mask, PLAY, self.phase)
        self.wave_timer = torch.where(mask, float(R.WAVE_DURATION), self.wave_timer)
        self.wave_num = self.wave_num + mask.long()
        grow = mask & (self.pizza_goal < R.PIZZA_GOAL_MAX)
        self.pizza_goal = torch.where(grow, (self.pizza_goal + R.PIZZA_GOAL_INCREMENT).clamp(max=R.PIZZA_GOAL_MAX),
                                      self.pizza_goal)
        self.extra = self.extra + (mask & ~grow).long()
        self.round_p = torch.where(mask, 0, self.round_p)
        self.dim = torch.where(mask, 1, self.dim)
        self._respawn(mask)
        self.p_weapon = torch.where(mask, weapon, self.p_weapon)
        self.last_weapon = torch.where(mask, weapon, self.last_weapon)
        layout = self._layout_index(wave)
        self._spawn_wave(mask, malus, layout, wave)
        self._apply_malus(mask, malus)
        self._new_round_bonus(mask, bonus, layout, wave)
        self.last_bonus = torch.where(mask, bonus, self.last_bonus)

    def _spawn_wave(self, mask, malus, layout, wave):
        """``spawn(extra)`` plus the malus enemies, from the layout pool."""
        lay, f = self.layout, self.dtype
        m2 = mask[:, None]
        # Resources (drops, enemies, projectiles cleared).
        kind = lay["res_kind"][layout]
        self.res_alive = torch.where(m2, lay["res_alive"][layout], self.res_alive)
        self.res_kind = torch.where(m2, kind, self.res_kind)
        self.res_rx = torch.where(m2, lay["res_rx"][layout], self.res_rx)
        self.res_ry = torch.where(m2, lay["res_ry"][layout], self.res_ry)
        self.res_hp = torch.where(m2, self.t_res_hp[kind], self.res_hp)
        self.res_hit_timer = torch.where(m2, 0.0, self.res_hit_timer)
        self.rdrop_alive = self.rdrop_alive & ~m2
        self.rdrop_count = torch.where(mask, 0, self.rdrop_count)
        self.edrop_alive = self.edrop_alive & ~m2
        self.edrop_count = torch.where(mask, 0, self.edrop_count)
        self.proj_alive = self.proj_alive & ~m2
        # Enemies: squids, tomatoes, then invasion or giant squids, compact per game.
        ext = self.extra.clamp(max=self.max_extra)
        nsq = (R.BASE_SQUIDS + ext)[:, None]
        nto = (R.BASE_TOMATOES + ext)[:, None]
        invasion = (malus == R.SQUID_INVASION)[:, None]
        giants = (malus == R.GIANT_SQUIDS)[:, None]
        alien = (malus == R.ALIEN_TOMATOES)[:, None]
        s = self.t_slot_e[None, :]
        is_sq = s < nsq
        is_to = ~is_sq & (s < nsq + nto)
        g = s - nsq - nto
        n_extra = torch.where(invasion, R.INVASION_SQUIDS, torch.where(giants, R.GIANT_SQUID_COUNT, 0))
        is_ex = (g >= 0) & (g < n_extra)
        i_sq = s.clamp(max=self.squid_spots - 1).expand(self.n, -1)
        i_to = (s - nsq).clamp(0, self.tomato_slots - 1)
        i_inv = g.clamp(0, R.INVASION_SQUIDS - 1)
        i_gi = g.clamp(0, R.GIANT_SQUID_COUNT - 1)

        def spot(group, index):
            return tuple(lay[f"{group}_{k}"][layout].gather(1, index) for k in ("x", "y", "ok"))

        sq, to, inv, gi = spot("squid", i_sq), spot("tomato", i_to), spot("invasion", i_inv), spot("giant", i_gi)
        x = torch.where(is_sq, sq[0], torch.where(is_to, to[0], torch.where(invasion, inv[0], gi[0])))
        y = torch.where(is_sq, sq[1], torch.where(is_to, to[1], torch.where(invasion, inv[1], gi[1])))
        ok = torch.where(is_sq, sq[2] & ~giants, torch.where(is_to, to[2], is_ex & torch.where(invasion, inv[2], gi[2])))
        giant = is_ex & giants
        u = wave["enemy"]
        e2 = m2.expand(-1, self.enemy_slots)

        def put(name, value):
            setattr(self, name, torch.where(e2, value, getattr(self, name)))

        zero = torch.zeros_like(x)
        put("en_alive", ok)
        put("en_kind", torch.where(is_to, R.TOMATO_ENEMY, R.SQUID))
        put("en_giant", giant)
        put("en_x", x)
        put("en_y", y)
        put("en_rx", _trunc(x))
        put("en_ry", _trunc(y))
        put("en_size", torch.where(is_to, R.TOMATO_SIZE, torch.where(giant, GIANT_SIZE, R.SQUID_SIZE)))
        hp = torch.where(is_to, zero + R.TOMATO_HP,
                         torch.where(giant, zero + R.SQUID_HP * R.GIANT_HP_FACTOR, zero + R.SQUID_HP))
        put("en_hp", hp)
        put("en_max_hp", hp)
        put("en_hit_timer", zero)
        put("en_dim", torch.where(is_to, torch.where(alien, 0, 1), torch.where(is_ex & invasion, 1, 0)))
        put("en_shoot_cd", torch.where(is_to, zero, _uniform(u, 0, 2)))
        put("en_timer", torch.where(is_to, _uniform(u, 0.5, 1.5), zero))
        for name in ("en_move_timer", "en_wx", "en_wy", "en_vx", "en_vy"):
            put(name, zero)
        put("en_move_state", torch.zeros_like(self.en_move_state))  # WANDER (squids), 0 (tomatoes)
        put("en_state", torch.zeros_like(self.en_state))  # IDLE (tomatoes), 0 (squids)
        self.en_count = torch.where(mask, (nsq + nto + n_extra)[:, 0], self.en_count)

    def _apply_malus(self, mask, malus):
        """``MalusManager.new_round`` minus the enemies (spawned by ``_spawn_wave``)."""
        m2 = mask[:, None]
        self.oven_dim = torch.where(mask, torch.where(malus == R.OVEN_DIMENSION, 0, 1), self.oven_dim)
        self.items_flee = torch.where(mask, malus == R.FLEEING_ITEMS, self.items_flee)
        self.portal_x = torch.where(m2, self.t_portal_x0.to(self.dtype), self.portal_x)
        self.portal_y = torch.where(m2, self.t_portal_y0.to(self.dtype), self.portal_y)
        self.portal_rx = torch.where(m2, self.t_portal_x0, self.portal_rx)
        self.portal_ry = torch.where(m2, self.t_portal_y0, self.portal_ry)
        self.portal_moving = torch.where(m2, (malus == R.MOVING_PORTALS)[:, None], self.portal_moving)
        self.malus = torch.where(mask, malus, self.malus)

    def _new_round_bonus(self, mask, bonus, layout, wave):
        """``BonusManager.new_round``: bombs and pills from the layout spots."""
        lay = self.layout
        m2 = mask[:, None]
        ub = wave["bomb"]
        count = R.BOMBS_COUNT_MIN + (ub[:, 0] * (R.BOMBS_COUNT_MAX - R.BOMBS_COUNT_MIN + 1)).long()
        bombs = (bonus == R.BOMBS)[:, None] & (self.t_slot_b < count[:, None]) & lay["bomb_ok"][layout]
        self.bomb_alive = torch.where(m2, bombs, self.bomb_alive)
        self.bomb_attached = self.bomb_attached & ~m2
        self.bomb_rx = torch.where(m2, _trunc(lay["bomb_x"][layout]) - R.BOMB_SIZE // 2, self.bomb_rx)
        self.bomb_ry = torch.where(m2, _trunc(lay["bomb_y"][layout]) - R.BOMB_SIZE // 2, self.bomb_ry)
        self.bomb_dim = torch.where(m2, (ub[:, 1:] * 2).long().clamp(max=1), self.bomb_dim)
        self.bomb_timer = torch.where(m2, 0.0, self.bomb_timer)
        count = R.PILL_COUNT_MIN + (wave["pill"] * (R.PILL_COUNT_MAX - R.PILL_COUNT_MIN + 1)).long()
        pills = (bonus == R.PILLS)[:, None] & (self.t_slot_p < count[:, None]) & lay["pill_ok"][layout]
        self.pill_alive = torch.where(m2, pills, self.pill_alive)
        self.pill_rx = torch.where(m2, _trunc(lay["pill_x"][layout]) - R.PILL_SIZE // 2, self.pill_rx)
        self.pill_ry = torch.where(m2, _trunc(lay["pill_y"][layout]) - R.PILL_SIZE // 2, self.pill_ry)
        self.pill_timer = torch.where(mask, 0.0, self.pill_timer)
        self.bonus = torch.where(mask, bonus, self.bonus)

    def _leave_shop(self, mask, wave):
        """SHOP -> ROULETTE -> next wave, with the roulette's exact outcome."""
        spin = _uniform(wave["roulette"].double(), R.ROULETTE_SPIN_MIN, R.ROULETTE_SPIN_MAX)
        ticks = 1 + (self.t_spin_totals <= spin[:, :, None]).sum(-1)
        count = self.t_spin_count[ticks.clamp(max=ROULETTE_TICKS)]
        malus, last_weapon, last_bonus = self.malus, self.last_weapon, self.last_bonus
        n_malus = torch.where(malus < 0, len(R.MALUSES), len(R.MALUSES) - 1)
        k = count[:, 0] % n_malus
        new_malus = k + ((malus >= 0) & (k >= malus)).long()
        k = count[:, 1] % (len(R.WEAPONS) - 1)
        new_weapon = k + (k >= last_weapon).long()
        n_bonus = torch.where(last_bonus < 0, len(R.BONUSES), len(R.BONUSES) - 1)
        k = count[:, 2] % n_bonus
        new_bonus = k + ((last_bonus >= 0) & (k >= last_bonus)).long()
        self.begin_wave(mask, new_malus, new_weapon, new_bonus, wave)

    # ------------------------------------------------------------------- shop
    def _can_buy_cards(self):
        """[N,3]: card affordable (phase SHOP)."""
        cost = self.upgrade_costs.gather(1, self.shop_cards)
        return (self.phase == SHOP)[:, None] & (self.pizzas_made[:, None] >= cost)

    def _buy(self, mask, card, u, wave, ev):
        """``Engine.buy(card)`` in the games of ``mask`` (phase SHOP)."""
        up = self.shop_cards.gather(1, card[:, None])[:, 0]
        cost = self.upgrade_costs.gather(1, up[:, None])[:, 0]
        ok = mask & (self.phase == SHOP) & (self.pizzas_made >= cost)
        self.pizzas_made = self.pizzas_made - torch.where(ok, cost, 0)
        self.p_vel = torch.where(ok & (up == R.SPEED), self.p_vel + R.UPGRADES[R.SPEED][1], self.p_vel)
        self.p_cap = torch.where(ok & (up == R.CAP), self.p_cap + R.UPGRADES[R.CAP][1], self.p_cap)
        self.cd_limit = torch.where(ok & (up == R.ATK_SPEED),
                                    (self.cd_limit - R.UPGRADES[R.ATK_SPEED][1]).clamp(min=R.MIN_CD_LIMIT), self.cd_limit)
        health = ok & (up == R.HEALTH)
        self.p_max_hp = torch.where(health, self.p_max_hp + R.UPGRADES[R.HEALTH][1], self.p_max_hp)
        self.p_hp = torch.where(health, torch.minimum(self.p_hp + R.UPGRADES[R.HEALTH][1], self.p_max_hp), self.p_hp)
        self.time_mult = torch.where(ok & (up == R.TIME), self.time_mult + R.UPGRADES[R.TIME][1], self.time_mult)
        bought = ok[:, None] & (self.t_upgrades == up[:, None])
        self.upgrade_costs = torch.where(bought, (cost[:, None] + R.UPGRADE_COST_STEP).clamp(max=R.UPGRADE_COST_MAX),
                                         self.upgrade_costs)
        # The card becomes choice(upgrades not on display), in index order.
        shown = (self.shop_cards[:, :, None] == self.t_upgrades).any(1)
        free = ~shown
        n_free = free.long().sum(1)
        j = (u * n_free).long().clamp(max=(n_free - 1).clamp(min=0))
        pick = free & ((free.long().cumsum(1) - 1) == j[:, None])
        other = (pick.long() * self.t_upgrades).sum(1)
        replace = (ok & (n_free > 0))[:, None] & (self.t_slot_c == card[:, None])
        self.shop_cards = torch.where(replace, other[:, None], self.shop_cards)
        self._add(ev, "buys", ok)
        leave = ok & ~self._can_buy_cards().any(1)
        if self._any(leave):
            self._leave_shop(leave, wave)

    # ------------------------------------------------------------- decisions
    def action_mask(self):
        """[N,24] valid actions, identical to ``rl.headless.env.action_mask``."""
        shop = self.phase == SHOP
        mask = torch.zeros(self.n, ACTION_COUNT, dtype=torch.bool, device=self.device)
        mask[:, :COOK_BASE] = ~shop[:, None]
        mask[:, COOK_BASE:BUY_BASE] = (self.phase == PLAY)[:, None] & self._can_cook()
        mask[:, BUY_BASE:] = self._can_buy_cards()
        return mask

    def step(self, actions):
        """One decision per game (``play_decision``); returns per-decision events (engine dtype)."""
        a = actions.to(device=self.device, dtype=torch.int64)
        ev = self._zero_events()
        play = self.phase == PLAY
        shop = self.phase == SHOP
        u_shop, wave = self.rand(self.n), self._wave_draws()
        buy = shop & (a >= BUY_BASE)
        if self._any(buy):
            self._buy(buy, (a - BUY_BASE).clamp(0, R.SHOP_CARDS - 1), u_shop, wave, ev)
        self.menu_open = self.menu_open & ~play
        is_move = a < COOK_BASE
        is_cook = ~is_move & (a < BUY_BASE)
        move = a.remainder(len(MOVES))
        dx = torch.where(is_move, self.t_move_dx[move], 0)
        dy = torch.where(is_move, self.t_move_dy[move], 0)
        interact = is_move & (a >= INTERACT_BASE)
        cook = torch.where(is_cook, a - COOK_BASE, -1)
        no_interact = torch.zeros_like(interact)
        no_cook = torch.full_like(cook, -1)
        live = play
        for i in range(self.frame_skip):
            if self._host_branches and not bool(live.any()):
                for _ in range(i, self.frame_skip):  # keep the random stream of a full decision
                    self._tick_draws()
                break
            self._tick(live, dx, dy, interact if i == 0 else no_interact, cook if i == 0 else no_cook, ev)
            live = live & (self.phase == PLAY)
        return ev

    # ------------------------------------------------------------------- tick
    def _tick(self, live, dx, dy, interact, cook, ev):
        """``Engine.tick`` in the games of ``live`` (phase PLAY).

        ``dx``/``dy`` in {-1, 0, 1} (int64), ``interact`` bool, ``cook`` slot or -1.
        """
        u_portal, u_enemy, u_order, u_wave, wave = self._tick_draws()
        self._add(ev, "ticks", live)
        cooking = live & (cook >= 0)
        slot = cook.clamp(min=0)
        can = cooking & self._can_cook().gather(1, slot[:, None])[:, 0]
        if self._any(can):
            self._cook(can, slot, ev)
        self.menu_open = self.menu_open | can
        trigger = live & ~cooking & interact & ~self.oven_active & ~self.menu_open & (self.cd <= 0)
        if self._any(trigger):
            self._trigger_weapon(trigger, ev)
        pill = self.pill_timer > 0
        one = torch.ones_like(self.p_speed_mult)
        self.p_speed_mult = torch.where(live, torch.where(pill, R.PILL_SPEED_MULTI, one), self.p_speed_mult)
        self.cd_limit_mult = torch.where(live, torch.where(pill, 1.0 / R.PILL_ATTACK_SPEED_MULTI, one),
                                         self.cd_limit_mult)
        moving = live & ~self.menu_open
        if self._any(moving):
            self._handle_input(moving, dx, dy)
        die = live & (self.p_hp <= 0)
        if self._any(die):
            self._respawn(die)
            self.dim = torch.where(die, 1, self.dim)
            self.wave_timer = torch.where(die, self.wave_timer - R.DEATH_PENALTY_TIME, self.wave_timer)
            self._add(ev, "deaths", die)
        go = live & ~die
        hp = self.p_hp
        self._world_update(go, u_portal, u_enemy, ev)
        self.wave_timer = torch.where(go, self.wave_timer - DT, self.wave_timer)
        self._orders_update(go, u_order, ev)
        self._bonus_update(go, ev)
        self._add(ev, "damage", torch.where(go, hp - self.p_hp, 0.0))
        self.menu_open = self.menu_open & ~(go & ~self.oven_active)
        end = go & (self.wave_timer <= 0)
        if self._any(end):
            self._end_wave(end, u_wave, wave, ev)

    def _can_cook(self):
        """[N,3]: ``can_cook(slot)`` without the phase test."""
        need = self.t_need[self.order_recipe]
        have = (self.p_inventory[:, None, :] >= need).all(-1)
        return self.oven_active[:, None] & self.order_alive & have

    def _cook(self, mask, slot, ev):
        s = slot[:, None]
        recipe = self.order_recipe.gather(1, s)[:, 0]
        timer = self.order_timer.gather(1, s)[:, 0]
        max_time = self.order_max_time.gather(1, s)[:, 0]
        self.p_inventory = self.p_inventory - self.t_need[recipe] * mask[:, None].long()
        points = _trunc(self.t_points[recipe] * (timer / max_time).clamp(min=0.5))
        points = torch.where(mask, points, 0)
        self.order_alive = self.order_alive & ~(mask[:, None] & (self.t_slot_o == s))
        self.score = self.score + points
        self.pizzas_made = self.pizzas_made + mask.long()
        self.round_p = self.round_p + mask.long()
        self._add(ev, "score", points)
        self._add(ev, "pizzas", mask)

    def _trigger_weapon(self, mask, ev):
        weapon = self.p_weapon
        limit = self.cd_limit * self.cd_limit_mult
        drum = mask & (weapon == R.DRUM)
        pan = mask & (weapon == R.PAN)
        sax = mask & (weapon == R.SAX)
        slow = (limit * R.SLOW_WEAPON_CD_FACTOR).clamp(min=R.SLOW_WEAPON_CD_MIN)
        self.cd = torch.where(drum, limit, torch.where(pan | sax, slow, self.cd))
        cx, cy = self.p_rx + HALF_PLAYER, self.p_ry + HALF_PLAYER
        if self._any(drum):
            self._hit(drum, cx, cy, R.DRUM_RES_DAMAGE, R.DRUM_ENEMY_DAMAGE, R.DRUM_RADIUS, ev)
        dx, dy = self.p_last_dx, self.p_last_dy
        length = (dx * dx + dy * dy).sqrt()
        flat = length == 0
        one = torch.ones_like(dx)
        ux = torch.where(flat, one, dx / length)
        uy = torch.where(flat, 0.0, dy / length)
        if self._any(pan):
            self.p_dash_vx = torch.where(pan, ux, self.p_dash_vx)
            self.p_dash_vy = torch.where(pan, uy, self.p_dash_vy)
            self.p_dash_timer = torch.where(pan, R.DASH_TIME, self.p_dash_timer)
            self.p_inv_timer = torch.where(pan, R.DASH_INV_TIME, self.p_inv_timer)
        if self._any(sax):
            new = _first(~self.note_alive) & sax[:, None]
            self.note_alive = self.note_alive | new
            self.note_x = torch.where(new, cx.to(self.dtype)[:, None], self.note_x)
            self.note_y = torch.where(new, cy.to(self.dtype)[:, None], self.note_y)
            self.note_dx = torch.where(new, ux[:, None], self.note_dx)
            self.note_dy = torch.where(new, uy[:, None], self.note_dy)
            self.note_timer = torch.where(new, 0.0, self.note_timer)

    def _handle_input(self, mask, dx, dy):
        dashing = mask & (self.p_dash_timer > 0)
        walk = mask & ~dashing
        f = self.dtype
        vx = ((dx > 0).long() - (dx < 0).long()).to(f)
        vy = ((dy > 0).long() - (dy < 0).long()).to(f)
        moving = walk & ((vx != 0) | (vy != 0))
        length = (vx * vx + vy * vy).sqrt()
        last_dx = torch.where(moving, vx / length, self.p_last_dx)
        last_dy = torch.where(moving, vy / length, self.p_last_dy)
        speed = self.p_vel
        wx = (self.p_x + last_dx * speed * self.p_speed_mult * DT).clamp(0, R.MAP_W - 80)
        wy = (self.p_y + last_dy * speed * self.p_speed_mult * DT).clamp(0, R.MAP_H - 80)
        sx = (self.p_x + self.p_dash_vx * R.DASH_SPEED * DT).clamp(0, R.MAP_W - PS)
        sy = (self.p_y + self.p_dash_vy * R.DASH_SPEED * DT).clamp(0, R.MAP_H - PS)
        x = torch.where(dashing, sx, torch.where(moving, wx, self.p_x))
        y = torch.where(dashing, sy, torch.where(moving, wy, self.p_y))
        moved = dashing | moving
        self.p_rx = torch.where(moved, _trunc(x), self.p_rx)
        self.p_ry = torch.where(moved, _trunc(y), self.p_ry)
        self.p_x, self.p_y = x, y
        self.p_last_dx, self.p_last_dy = last_dx, last_dy
        self.p_dash_timer = torch.where(dashing, self.p_dash_timer - DT, self.p_dash_timer)
        self.p_inv_timer = torch.where(walk, self.p_inv_timer - DT, self.p_inv_timer)

    # ------------------------------------------------------------------ combat
    def _route(self, src, free):
        """Assign the k-th true ``src`` [N,S] to the k-th true ``free`` [N,D].

        Returns ``take`` [N,D] and the source index [N,D] of every taken slot.
        """
        cum = src.long().cumsum(1)
        rank = free.long().cumsum(1) - 1
        take = free & (rank < cum[:, -1:])
        index = torch.searchsorted(cum, rank.clamp(min=0), right=True).clamp(max=src.shape[1] - 1)
        return take, index

    def _append_rdrops(self, src, kind, rx, ry):
        """Append resource drops (birth order) for the true entries of ``src``."""
        take, index = self._route(src, self.t_slot_r >= self.rdrop_count[:, None])
        self.rdrop_alive = self.rdrop_alive | take
        self.rdrop_kind = torch.where(take, kind.gather(1, index), self.rdrop_kind)
        self.rdrop_rx = torch.where(take, rx.gather(1, index), self.rdrop_rx)
        self.rdrop_ry = torch.where(take, ry.gather(1, index), self.rdrop_ry)
        self.rdrop_count = (self.rdrop_count + src.long().sum(1)).clamp(max=self.rdrop_slots)

    def _hit(self, mask, px, py, res_damage, enemy_damage, radius, ev):
        """``_hit_resources`` then ``_hit_enemies`` around (px, py) (int: exact, float: sqrt)."""
        m2 = mask[:, None]
        exact = not px.is_floating_point()
        px, py = px[:, None], py[:, None]

        def near(cx, cy):
            dx, dy = px - cx, py - cy
            if exact:
                return dx * dx + dy * dy < radius * radius
            return (dx * dx + dy * dy).sqrt() < radius

        kind = self.res_kind
        rcx = self.res_rx + self.t_res_w[kind] // 2
        rcy = self.res_ry + self.t_res_h[kind] // 2
        hit = m2 & self.res_alive & (self.dim == 0)[:, None] & (self.res_hit_timer <= 0) & near(rcx, rcy)
        self.res_hp = self.res_hp - hit.long() * res_damage
        self.res_hit_timer = torch.where(hit, R.HIT_COOLDOWN, self.res_hit_timer)
        broken = hit & (self.res_hp <= 0)
        self._append_rdrops(broken, self.t_res_drop[kind], self.res_rx, self.res_ry)
        self.res_alive = self.res_alive & ~broken
        self._add(ev, "harvested", broken.sum(1))
        ecx = self.en_rx + self.en_size // 2
        ecy = self.en_ry + self.en_size // 2
        hit = (m2 & self.en_alive & (self.en_dim == self.dim[:, None]) & (self.en_hit_timer <= 0) & near(ecx, ecy))
        self.en_hp = self.en_hp - hit.to(self.dtype) * enemy_damage
        self.en_hit_timer = torch.where(hit, R.HIT_COOLDOWN, self.en_hit_timer)
        killed = hit & (self.en_hp <= 0)
        drops = killed & (self.en_kind == R.TOMATO_ENEMY)
        take, index = self._route(drops, self.t_slot_d >= self.edrop_count[:, None])
        self.edrop_alive = self.edrop_alive | take
        self.edrop_rx = torch.where(take, self.en_rx.gather(1, index), self.edrop_rx)
        self.edrop_ry = torch.where(take, self.en_ry.gather(1, index), self.edrop_ry)
        self.edrop_dim = torch.where(take, self.dim[:, None], self.edrop_dim)
        self.edrop_count = (self.edrop_count + drops.long().sum(1)).clamp(max=self.edrop_slots)
        self.en_alive = self.en_alive & ~killed
        self._add(ev, "kills", killed.sum(1))

    def _take_damage(self, mask, amount):
        """``Player.take_damage`` (amount halved under the pill)."""
        ok = mask & ~(self.p_inv_timer > 0) & ~(self.p_dash_timer > 0)
        amount = torch.where(self.p_speed_mult > 1.1, amount / 2, torch.full_like(self.p_hp, amount))
        self.p_hp = torch.where(ok, self.p_hp - amount, self.p_hp)
        self.p_inv_timer = torch.where(ok, R.PLAYER_INV_TIME, self.p_inv_timer)

    # ---------------------------------------------------------------- world
    def _world_update(self, go, u_portal, u_enemy, ev):
        self.cd = torch.where(go, (self.cd - DT).clamp(min=0), self.cd)
        moving = go[:, None] & self.portal_moving
        if self._any(moving):
            self._portals_update(moving, u_portal)
        notes = go[:, None] & self.note_alive
        if self._any(notes):
            self._notes_update(notes, ev)
        pcx, pcy = self.p_rx + HALF_PLAYER, self.p_ry + HALF_PLAYER
        dash = go & (self.p_dash_timer > 0)
        if self._any(dash):
            self._hit(dash, pcx, pcy, R.DASH_RES_DAMAGE, R.DASH_ENEMY_DAMAGE, R.DASH_RADIUS, ev)
        # Portals: only the first touched portal can switch the dimension.
        prx, pry = self.p_rx[:, None], self.p_ry[:, None]
        qx, qy, size = self.portal_rx, self.portal_ry, R.PORTAL_SIZE
        touch = _collide(prx, pry, PS, PS, qx, qy, size, size)
        s = R.PORTAL_HITBOX_SHRINK // 2
        inner = _collide(prx, pry, PS, PS, qx + s, qy + s, size - 2 * s, size - 2 * s)
        touching = touch.any(1)
        switch = go & touching & ~self.in_portal & (_first(touch) & inner).any(1)
        self.dim = torch.where(switch, 1 - self.dim, self.dim)
        self.in_portal = torch.where(switch, True, self.in_portal & ~(go & ~touching))
        self.p_inv_timer = torch.where(switch, 0.2, self.p_inv_timer)
        go = go & ~switch
        dx, dy = R.OVEN_CX - pcx, R.OVEN_CY - pcy
        active = (self.dim == self.oven_dim) & (dx * dx + dy * dy < R.OVEN_ACTIVE_DIST ** 2)
        self.oven_active = torch.where(go, active, self.oven_active)
        self._resources_update(go, ev)
        self._enemies_update(go, u_enemy, ev)

    def _portals_update(self, moving, u):
        timer = self.portal_move_timer - DT
        renew = moving & (timer <= 0)
        timer = torch.where(renew, _uniform(u[..., 0], 0.5, 2.0), timer)
        stop = u[..., 1] < 0.2
        angle = _uniform(u[..., 2], 0, R.TAU)
        speed = _uniform(u[..., 3], 150, 250)
        tvx = torch.where(renew, torch.where(stop, 0.0, torch.cos(angle) * speed), self.portal_tvx)
        tvy = torch.where(renew, torch.where(stop, 0.0, torch.sin(angle) * speed), self.portal_tvy)
        t = DT * R.PORTAL_LERP
        vx = self.portal_vx * (1 - t) + tvx * t
        vy = self.portal_vy * (1 - t) + tvy * t
        x = (self.portal_x + vx * DT).clamp(R.PORTAL_MIN, R.PORTAL_MAX_X)
        y = (self.portal_y + vy * DT).clamp(R.PORTAL_MIN, R.PORTAL_MAX_Y)
        self.portal_move_timer = torch.where(moving, timer, self.portal_move_timer)
        self.portal_tvx, self.portal_tvy = tvx, tvy
        self.portal_vx = torch.where(moving, vx, self.portal_vx)
        self.portal_vy = torch.where(moving, vy, self.portal_vy)
        self.portal_x = torch.where(moving, x, self.portal_x)
        self.portal_y = torch.where(moving, y, self.portal_y)
        self.portal_rx = torch.where(moving, _trunc(x), self.portal_rx)
        self.portal_ry = torch.where(moving, _trunc(y), self.portal_ry)

    def _notes_update(self, alive, ev):
        timer = torch.where(alive, self.note_timer + DT, self.note_timer)
        fly = alive & (timer < R.NOTE_TIME)
        self.note_x = torch.where(fly, self.note_x + self.note_dx * R.NOTE_SPEED * DT, self.note_x)
        self.note_y = torch.where(fly, self.note_y + self.note_dy * R.NOTE_SPEED * DT, self.note_y)
        self.note_timer = timer
        boom = alive & ~fly
        first = _first(boom)
        bx = torch.where(first, self.note_x, 0.0).sum(1)
        by = torch.where(first, self.note_y, 0.0).sum(1)
        self.note_alive = self.note_alive & ~boom
        exploding = boom.any(1)
        if self._any(exploding):
            self._hit(exploding, bx, by, R.NOTE_RES_DAMAGE, R.NOTE_ENEMY_DAMAGE, R.NOTE_RADIUS, ev)

    def _flee(self, mask, rx, ry):
        """``Drop.flee`` for the drops of ``mask``; returns the new (rx, ry)."""
        if not self._any(mask):
            return rx, ry
        cx, cy = rx + HALF_DROP, ry + HALF_DROP
        dx = cx - (self.p_rx + HALF_PLAYER)[:, None]
        dy = cy - (self.p_ry + HALF_PLAYER)[:, None]
        dsq = dx * dx + dy * dy
        flee = mask & (dsq < R.DROP_FLEE_DIST ** 2) & (dsq > 0)
        dxf, dyf = dx.to(self.dtype), dy.to(self.dtype)
        length = (dxf * dxf + dyf * dyf).sqrt()
        fx = cx + dxf / length * R.DROP_FLEE_SPEED * DT
        fy = cy + dyf / length * R.DROP_FLEE_SPEED * DT
        fx = torch.where(flee, fx, 0.0)
        fy = torch.where(flee, fy, 0.0)
        return (torch.where(flee, _trunc(fx) - HALF_DROP, rx), torch.where(flee, _trunc(fy) - HALF_DROP, ry))

    def _pick(self, collide, kind, kinds, ev):
        """``_pick`` of colliding drops in slot order, per ingredient up to ``cap``."""
        picked = torch.zeros_like(collide)
        inventory = list(self.p_inventory.unbind(1))
        for k in kinds:
            mine = collide & (kind == k) if kind is not None else collide
            rank = mine.long().cumsum(1) - mine.long()
            take = mine & (rank < (self.p_cap - inventory[k])[:, None])
            picked = picked | take
            inventory[k] = inventory[k] + take.long().sum(1)
        self.p_inventory = torch.stack(inventory, 1)
        self._add(ev, "picked", picked.sum(1))
        return picked

    def _resources_update(self, go, ev):
        m2 = go[:, None]
        alive = m2 & self.res_alive
        self.res_hit_timer = torch.where(alive, (self.res_hit_timer - DT).clamp(min=0), self.res_hit_timer)
        visible = m2 & self.rdrop_alive & ((self.dim == 1)[:, None] == (self.rdrop_kind == R.TOMATO))
        if not self._any(visible):
            return
        self.rdrop_rx, self.rdrop_ry = self._flee(visible & self.items_flee[:, None], self.rdrop_rx, self.rdrop_ry)
        collide = visible & _collide(self.p_rx[:, None], self.p_ry[:, None], PS, PS, self.rdrop_rx, self.rdrop_ry,
                                     R.DROP_SIZE, R.DROP_SIZE)
        self.rdrop_alive = self.rdrop_alive & ~self._pick(collide, self.rdrop_kind, range(3), ev)

    def _enemies_update(self, go, u, ev):
        """Oven push, squid/tomato AI (vectorised), separation (sequential), contacts, projectiles, drops."""
        f = self.dtype
        alive = self.en_alive
        act = alive & go[:, None]
        X, Y, size = self.en_x, self.en_y, self.en_size
        pcx = (self.p_rx + HALF_PLAYER)[:, None]
        pcy = (self.p_ry + HALF_PLAYER)[:, None]
        pcxf, pcyf = pcx.to(f), pcy.to(f)
        # Oven push (enemies of the oven's dimension).
        odx, ody = X - R.OVEN_CX, Y - R.OVEN_CY
        od = (odx * odx + ody * ody).sqrt()
        push = act & (self.en_dim == self.oven_dim[:, None]) & (od < R.OVEN_ENEMY_PUSH_RADIUS)
        Xp = torch.where(push, X + odx / od * R.OVEN_ENEMY_PUSH_SPEED * DT, X)
        Yp = torch.where(push, Y + ody / od * R.OVEN_ENEMY_PUSH_SPEED * DT, Y)
        rx = torch.where(push, _trunc(Xp), self.en_rx)
        ry = torch.where(push, _trunc(Yp), self.en_ry)
        visible = self.en_dim == self.dim[:, None]
        squid = act & (self.en_kind == R.SQUID)
        tomato = act & (self.en_kind == R.TOMATO_ENEMY) & visible
        moved = squid | tomato
        self.en_hit_timer = torch.where(moved, (self.en_hit_timer - DT).clamp(min=0), self.en_hit_timer)
        cx, cy = rx + size // 2, ry + size // 2
        zero = torch.zeros_like(X)

        # --- squids: portal flee, wander/adjust state machine, shooting
        pdx = cx[:, :, None] - (self.portal_rx + HALF_PORTAL)[:, None, :]
        pdy = cy[:, :, None] - (self.portal_ry + HALF_PORTAL)[:, None, :]
        within = pdx * pdx + pdy * pdy < R.SQUID_PORTAL_FLEE_DIST ** 2
        first = _first(within)
        fdx = (pdx * first).sum(2).to(f)
        fdy = (pdy * first).sum(2).to(f)
        flen = (fdx * fdx + fdy * fdy).sqrt()
        flee = squid & within.any(2) & (flen > 0)
        free = squid & ~flee
        force = ~visible
        mt = torch.where(free, self.en_move_timer - DT, self.en_move_timer)
        expired = free & (mt <= 0)
        to_wander = expired & (self.en_move_state == R.ADJUST) & ~force
        other = expired & ~to_wander
        state = torch.where(other, torch.where(force, R.WANDER, R.ADJUST), self.en_move_state)
        state = torch.where(flee | to_wander, R.WANDER, state)
        self.en_move_state = state
        self.en_move_timer = torch.where(to_wander, _uniform(u[..., 0], 0.3, 0.8),
                                         torch.where(other, _uniform(u[..., 0], 0.5, 1.0), mt))
        wander = to_wander | (other & force)
        wx, wy = _uniform(u[..., 1], -1, 1), _uniform(u[..., 2], -1, 1)
        wl = (wx * wx + wy * wy).sqrt()
        self.en_wx = torch.where(wander, torch.where(wl > 0, wx / wl, wx), self.en_wx)
        self.en_wy = torch.where(wander, torch.where(wl > 0, wy / wl, wy), self.en_wy)
        seen = free & ~force
        sdx, sdy = pcxf - Xp, pcyf - Yp
        dist = (sdx * sdx + sdy * sdy).sqrt()
        adjust = seen & (state == R.ADJUST) & (dist > 0)
        away = adjust & (dist < R.SQUID_NEAR)
        closer = adjust & (dist > R.SQUID_FAR)
        wandering = (seen & (state != R.ADJUST)) | (free & force)
        vx = torch.where(away, -(sdx / dist) * R.SQUID_AWAY_SPEED,
                         torch.where(closer, sdx / dist * R.SQUID_CLOSER_SPEED,
                                     torch.where(wandering, self.en_wx * R.SQUID_WANDER_SPEED, zero)))
        vy = torch.where(away, -(sdy / dist) * R.SQUID_AWAY_SPEED,
                         torch.where(closer, sdy / dist * R.SQUID_CLOSER_SPEED,
                                     torch.where(wandering, self.en_wy * R.SQUID_WANDER_SPEED, zero)))
        vx = torch.where(flee, fdx / flen * R.SQUID_FLEE_SPEED, vx)
        vy = torch.where(flee, fdy / flen * R.SQUID_FLEE_SPEED, vy)
        shoot_cd = torch.where(seen, self.en_shoot_cd - DT, self.en_shoot_cd)
        shoot = seen & (shoot_cd <= 0) & (dist < R.SQUID_SHOOT_DIST)
        self.en_shoot_cd = torch.where(shoot, R.SQUID_SHOOT_CD, shoot_cd)
        if self._any(shoot):
            self._spawn_projectiles(shoot, cx - 24, cy - 24, pcx, pcy)

        # --- tomatoes: jump / charge state machine (visible ones only)
        tdx, tdy = pcxf - Xp, pcyf - Yp
        tdist = (tdx * tdx + tdy * tdy).sqrt()
        timer = torch.where(tomato, self.en_timer - DT, self.en_timer)
        s = self.en_state
        due = timer <= 0
        tvx, tvy = self.en_vx, self.en_vy
        rolling = tomato & ((s == R.JUMP) | (s == R.ROLLING))
        Xm = torch.where(rolling, Xp + tvx * DT, Xp)
        Ym = torch.where(rolling, Yp + tvy * DT, Yp)
        idle = tomato & (s == R.IDLE)
        idle_due = idle & due
        charge = idle_due & (tdist < R.TOMATO_ATTACK_DIST)
        jump_prep = tomato & (s == R.JUMP_PREP) & due
        jump_end = tomato & (s == R.JUMP) & due
        land_end = tomato & (s == R.LAND) & due
        charge_end = tomato & (s == R.CHARGE_PREP) & due
        roll_end = tomato & (s == R.ROLLING) & due
        new_state = torch.where(charge, R.CHARGE_PREP, torch.where(idle_due, R.JUMP_PREP, s))
        new_state = torch.where(jump_prep, R.JUMP, torch.where(jump_end, R.LAND, new_state))
        new_state = torch.where(land_end | roll_end, R.IDLE, torch.where(charge_end, R.ROLLING, new_state))
        self.en_state = new_state
        timer = torch.where(charge, 1.0, torch.where(idle_due, 0.5, timer))
        timer = torch.where(jump_prep, 0.5, torch.where(jump_end, 0.2, timer))
        timer = torch.where(land_end, _uniform(u[..., 0], 0.5, 1.0), timer)
        timer = torch.where(charge_end | roll_end, 1.5, timer)
        self.en_timer = timer
        angle = _uniform(u[..., 0], 0, 6.28)
        stop = idle | jump_end
        aim = charge_end & (tdist > 0)
        tvx = torch.where(stop, zero, torch.where(jump_prep, torch.cos(angle) * R.TOMATO_JUMP_SPEED,
                                                    torch.where(aim, tdx / tdist * R.TOMATO_ROLL_SPEED, tvx)))
        tvy = torch.where(stop, zero, torch.where(jump_prep, torch.sin(angle) * R.TOMATO_JUMP_SPEED,
                                                    torch.where(aim, tdy / tdist * R.TOMATO_ROLL_SPEED, tvy)))
        self.en_vx, self.en_vy = tvx, tvy

        # --- separation, in list order: earlier enemies already moved (Gauss-Seidel).
        # The force sum is a cumulative sum: on the CPU it adds the terms left to right,
        # like the reference loop (bit-exact).
        center_x = torch.where(tomato, Xm, Xp)
        center_y = torch.where(tomato, Ym, Yp)
        is_squid = self.en_kind == R.SQUID
        radius = torch.where(is_squid, R.SQUID_SEP_DIST, R.TOMATO_SEP_DIST).to(f)
        strength = torch.where(is_squid, R.SQUID_SEP_FORCE, R.TOMATO_SEP_FORCE).to(f)
        cur_x, cur_y = X.clone(), Y.clone()
        hi = self.enemy_slots
        columns = range(hi)
        if self._host_branches:
            hi = max(1, int(self.en_count.max()))
            # Columns where no game moves an enemy and none is pushed keep their positions.
            busy = (moved | push)[:, :hi].any(0).tolist()
            columns = [j for j in range(hi) if busy[j]]
        others = alive[:, :hi]
        for j in columns:
            ddx, ddy = center_x[:, j:j + 1] - cur_x[:, :hi], center_y[:, j:j + 1] - cur_y[:, :hi]
            d = (ddx * ddx + ddy * ddy).sqrt()
            near = others & self.t_not_self[j, :hi] & (d < radius[:, j:j + 1]) & (d > 0)
            k = strength[:, j:j + 1] / d.clamp(min=1)
            sx = torch.where(near, ddx / d * k, 0.0).cumsum(1)[:, -1]
            sy = torch.where(near, ddy / d * k, 0.0).cumsum(1)[:, -1]
            sq, tm = squid[:, j], tomato[:, j]
            cxj, cyj = center_x[:, j], center_y[:, j]
            cur_x[:, j] = torch.where(sq, cxj + (vx[:, j] + sx * R.SQUID_SEP_GAIN) * DT,
                                      torch.where(tm, cxj + sx * DT, Xp[:, j]))
            cur_y[:, j] = torch.where(sq, cyj + (vy[:, j] + sy * R.SQUID_SEP_GAIN) * DT,
                                      torch.where(tm, cyj + sy * DT, Yp[:, j]))
        self.en_x, self.en_y = cur_x, cur_y
        self.en_rx = torch.where(squid, _trunc(cur_x), torch.where(tomato, _trunc(cur_x) - size // 2, rx))
        self.en_ry = torch.where(squid, _trunc(cur_y), torch.where(tomato, _trunc(cur_y) - size // 2, ry))

        # --- contact damage (the first contact sets the invulnerability)
        prx, pry = self.p_rx[:, None], self.p_ry[:, None]
        contact = moved & visible & _collide(prx, pry, PS, PS, self.en_rx, self.en_ry, size, size)
        self._take_damage(go & contact.any(1), R.CONTACT_DAMAGE)

        # --- projectiles (including the ones fired this tick)
        pa = go[:, None] & self.proj_alive
        x = torch.where(pa, self.proj_x + self.proj_vx * DT, self.proj_x)
        y = torch.where(pa, self.proj_y + self.proj_vy * DT, self.proj_y)
        self.proj_x, self.proj_y = x, y
        self.proj_rx = torch.where(pa, _trunc(x), self.proj_rx)
        self.proj_ry = torch.where(pa, _trunc(y), self.proj_ry)
        self.proj_timer = torch.where(pa, self.proj_timer + DT, self.proj_timer)
        expired = pa & (self.proj_timer > R.PROJECTILE_LIFETIME)
        odx, ody = x - R.OVEN_CX, y - R.OVEN_CY
        oven = pa & ~expired & (self.proj_dim == self.oven_dim[:, None]) & \
            ((odx * odx + ody * ody).sqrt() < R.OVEN_PROJECTILE_RADIUS)
        hit = pa & ~expired & ~oven & (self.proj_dim == self.dim[:, None]) & \
            _collide(prx, pry, PS, PS, self.proj_rx, self.proj_ry, self.proj_size, self.proj_size)
        self._take_damage(go & hit.any(1), R.PROJECTILE_DAMAGE)
        self.proj_alive = self.proj_alive & ~(expired | oven | hit)

        # --- enemy drops (tomatoes killed by the instruments)
        visible = go[:, None] & self.edrop_alive & (self.edrop_dim == self.dim[:, None])
        if self._any(visible):
            self.edrop_rx, self.edrop_ry = self._flee(visible & self.items_flee[:, None], self.edrop_rx, self.edrop_ry)
            collide = visible & _collide(prx, pry, PS, PS, self.edrop_rx, self.edrop_ry, R.DROP_SIZE, R.DROP_SIZE)
            self.edrop_alive = self.edrop_alive & ~self._pick(collide, None, (R.TOMATO,), ev)

    def _spawn_projectiles(self, shoot, x0, y0, tx, ty):
        """``Projectile(x0, y0, tx, ty, dim, giant)`` for every shooter, in free slots."""
        f = self.dtype
        take, index = self._route(shoot, ~self.proj_alive)
        dx = (tx - x0).to(f)
        dy = (ty - y0).to(f)
        length = (dx * dx + dy * dy).sqrt()
        flat = length == 0
        vx = torch.where(flat, torch.ones_like(dx), dx / length * R.PROJECTILE_SPEED)
        vy = torch.where(flat, 0.0, dy / length * R.PROJECTILE_SPEED)
        size = torch.where(self.en_giant, R.PROJECTILE_SIZE * 3, R.PROJECTILE_SIZE)

        def put(name, value):
            setattr(self, name, torch.where(take, value.gather(1, index), getattr(self, name)))

        put("proj_x", x0.to(f))
        put("proj_y", y0.to(f))
        put("proj_rx", x0)
        put("proj_ry", y0)
        put("proj_vx", vx)
        put("proj_vy", vy)
        put("proj_size", size)
        put("proj_dim", self.en_dim)
        self.proj_timer = torch.where(take, 0.0, self.proj_timer)
        self.proj_alive = self.proj_alive | take

