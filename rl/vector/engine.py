"""Batched torch port of ``rl.headless.engine``: thousands of Cuisto Bongo games at once.

``rl/headless/engine.py`` is the specification. Every tick follows its update
order and floating point formulas (``sqrt(x*x + y*y)``, left-to-right products,
``int()`` truncation of rects, rect centre ``rx + w // 2``); decisions follow
``rl.headless.env.play_decision``. Entity lists become fixed-capacity slots:

=====================  ==============================  ===================================
state                  capacity (default)              slot order
=====================  ==============================  ===================================
orders                 3                               order slot
portals                4                               portal index
notes (saxophone)      NOTE_SLOTS = 4                  any free slot
resources              RES_SLOTS = 205                 list order (removal = dead slot)
resource drops         RDROP_SLOTS = 205 + 40          birth order, ``rdrop_count``
enemies                ENEMY_SLOTS = 27 + 40 + 8       list order, ``en_count``
enemy drops            EDROP_SLOTS = 40                birth order, ``edrop_count``
projectiles            PROJ_SLOTS = 48                 any free slot
bombs / pills          8 / 8                           list order
=====================  ==============================  ===================================

All state is tensor attributes (``f`` = engine dtype, ``i`` = int64, ``b`` =
bool; ``-1`` stands for ``None``), listed in ``state_spec``. ``step`` never
reads a device value on the host when ``_host_branches`` is off (default off
the CPU): no ``.item()``, no data-dependent shape, every branch is a mask, so it
can be captured in a CUDA graph. On the CPU, ``_host_branches`` skips work no
game needs (same results, same random stream).

Randomness: every draw goes through ``rand(*shape)`` with fixed shapes per
tick and per decision (see ``_tick_draws`` / ``_wave_draws``), so tests can
inject the same numbers into the headless engine (``Engine._rng_for``).
``uniform(a, b)`` is ``a + (b - a) * u``, ``choice``/``randint``/``sample`` use
``int(u * n)`` as ``_randbelow(n)`` and the algorithms of ``random.Random``.

Exactness: in float64 on the CPU, one tick from a loaded headless state
reproduces the headless tick bit for bit, except ``torch.cos``/``torch.sin``
versus ``math`` (portal and tomato jump directions, at most a few ulps; the
parity test uses a 1e-9 tolerance on floats, ints and bools are exact). On
CUDA, separation forces are also summed in a different order. Circle tests on
integer centres compare squared integers (equal to ``math.hypot``); the
saxophone note explosion compares ``sqrt`` with the radius where the game uses
``math.hypot`` (they can differ by one ulp).

Documented approximations (decision semantics are otherwise exact):

* wave layouts come from a pool generated by the headless spawn code with the
  default portal positions (``rl.vector.layouts``); per-entity random values
  (squid ``shoot_cd``, tomato timers, bomb count and dimensions, pill count)
  are drawn here with the game's distributions;
* ``extra`` above ``max_extra`` spawns ``max_extra`` extra enemies;
* capacities: a projectile or note without a free slot is dropped (the game
  rules keep at most 4 notes and, in practice, far fewer than 48 projectiles);
* at most one note explodes per tick and simultaneous bomb explosions (bombs
  attached on the same tick, hence at the same place) act as one: both are
  guaranteed by the game rules (weapon cooldown >= 13 ticks, attached bombs
  follow the player).
"""

